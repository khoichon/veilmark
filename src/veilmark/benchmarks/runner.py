"""Robustness benchmark runner.

For every (media sample, seed) a fresh random watermark id and signed payload are
embedded with ephemeral benchmark keys; every attack is applied to the watermarked
copy (positive) and to the original (negative), and blind detection is run on
both. Results are written as JSONL (one record per detection), aggregated JSON,
CSV and a self-contained HTML report.

Seeds drive only *simulation* randomness (crop positions, noise, payload text).
Keys and watermark ids are generated by the normal cryptographic code paths.
"""

from __future__ import annotations

import json
import os
import shutil
import tempfile
import time
import traceback
import zlib
from collections.abc import Callable
from concurrent.futures import ProcessPoolExecutor, as_completed
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from veilmark.benchmarks import attacks as atk
from veilmark.benchmarks import datasets

PROFILES: dict[str, dict[str, Any]] = {
    "quick": {
        "image_attacks": atk.QUICK_ATTACKS,
        "max_images": 4,
        "seeds": 1,
        "video_attacks": atk.QUICK_VIDEO_ATTACKS,
        "max_videos": 1,
    },
    "standard": {
        "image_attacks": None,
        "max_images": None,
        "seeds": 2,
        "video_attacks": None,
        "max_videos": None,
    },
    "full": {
        "image_attacks": None,
        "max_images": None,
        "seeds": 4,
        "video_attacks": None,
        "max_videos": None,
    },
}


@dataclass
class BenchConfig:
    out_dir: Path
    split: str = "heldout"
    profile: str = "standard"
    media: str = "image"  # image | video | both
    seeds: int | None = None
    image_names: list[str] | None = None
    attack_names: list[str] | None = None
    video_attack_names: list[str] | None = None
    strength: float = 1.0
    workers: int = max(1, (os.cpu_count() or 2) - 1)
    keep_media: bool = False
    extra_images: list[Path] = field(default_factory=list)
    extra_videos: list[Path] = field(default_factory=list)


def _setup_home(home: Path) -> None:
    from veilmark.api import Veilmark

    vm = Veilmark(home)
    vm.keystore.generate_pattern_key("bench")
    trusted = vm.keystore.generate_identity("bench-trusted", None)
    vm.trust.add(trusted.public_bytes, "bench-trusted")
    # An identity that is deliberately NOT in the trust list (forgery tests).
    vm.keystore.generate_identity("bench-untrusted", None)


def _stable(s: str) -> int:
    """Process-independent seed component (``hash()`` is randomised per process)."""
    return zlib.crc32(s.encode())


def _text(rng: np.random.Generator) -> str:
    words = ["photo", "by", "studio", "north", "archive", "2026", "press", "lab", "field", "shot"]
    return " ".join(rng.choice(words, size=3))[:20]


# ------------------------------------------------------------------ images


def _image_job(
    home: str, sample_name: str, extra_path: str | None, seed: int, attack_names: list[str], strength: float
) -> list[dict[str, Any]]:
    from veilmark.api import Veilmark, WatermarkSpec
    from veilmark.image.io import ImageData

    vm = Veilmark(Path(home))
    if extra_path:
        from veilmark.image import io as image_io

        rgb = image_io.load(Path(extra_path)).rgb
        split, kind = "user", "user"
    else:
        smp = next(s for s in datasets.IMAGES if s.name == sample_name)
        rgb, split, kind = smp.load(), smp.split, smp.kind
    rng = np.random.default_rng([seed, _stable(sample_name)])
    text = _text(rng)
    spec = WatermarkSpec(text=text, strength=strength, identity="bench-trusted")
    out, emb = vm.embed_image_data(ImageData(rgb), spec)
    wid = bytes.fromhex(emb.watermark_id)
    records = []
    base = {
        "media": "image",
        "sample": sample_name,
        "split": split,
        "kind": kind,
        "seed": seed,
        "width": int(rgb.shape[1]),
        "height": int(rgb.shape[0]),
        "chip_px": emb.chip_px,
        "psnr_db": emb.psnr_db,
        "ssim": emb.ssim,
        "payload_bytes": emb.payload_bytes,
    }
    for name in attack_names:
        a = next(x for x in atk.IMAGE_ATTACKS if x.name == name)
        for polarity, src in (("positive", out.rgb), ("negative", rgb)):
            arng = np.random.default_rng([seed, _stable(sample_name + name)])
            t0 = time.perf_counter()
            try:
                attacked = a.fn(src, arng)
                t_att = time.perf_counter() - t0
                t1 = time.perf_counter()
                rep = vm.detect_image_data(ImageData(attacked), f"{sample_name}/{name}")
                dt = time.perf_counter() - t1
                v = rep.verification or {}
                rec = {
                    **base,
                    "attack": name,
                    "group": a.group,
                    "expected": a.expected,
                    "params": a.params,
                    "polarity": polarity,
                    "status": rep.status,
                    "detected": rep.detected,
                    "id_match": rep.watermark_id == wid.hex() if polarity == "positive" else False,
                    "payload_match": bool(rep.payload and rep.payload.get("text") == text)
                    if polarity == "positive"
                    else False,
                    "wrong_payload": bool(
                        polarity == "positive" and rep.payload and rep.payload.get("text") != text
                    ),
                    "signature": v.get("signature"),
                    "authentic": rep.authentic,
                    "sync_z": rep.confidence.get("sync_z"),
                    "detect_seconds": round(dt, 3),
                    "attack_seconds": round(t_att, 3),
                    "attacked_size": [int(attacked.shape[1]), int(attacked.shape[0])],
                    "geometry": rep.geometry,
                }
            except Exception as e:
                rec = {
                    **base,
                    "attack": name,
                    "polarity": polarity,
                    "error": f"{type(e).__name__}: {e}",
                    "trace": traceback.format_exc(limit=3),
                }
            records.append(rec)
    # Forgery / integrity checks on this sample (no attack applied).
    records += _forgery_checks(vm, rgb, text, base)
    return records


def _forgery_checks(vm: Any, rgb: np.ndarray, text: str, base: dict[str, Any]) -> list[dict[str, Any]]:
    """Embed deliberately forged payloads; the verifier must reject each one."""
    from veilmark.crypto import payload as pl
    from veilmark.crypto import trust
    from veilmark.image.io import ImageData
    from veilmark.watermark import engine
    from veilmark.watermark.pattern import KeyedPatterns

    out = []
    trusted = vm.keystore.identity("bench-trusted").unlock(None)
    untrusted = vm.keystore.identity("bench-untrusted").unlock(None)
    pats = KeyedPatterns(vm.keystore.pattern_key().key_bytes)
    wid = os.urandom(8)
    good = trust.sign(wid, pl.Payload(text=text, timestamp=int(time.time())), trusted)
    raw = bytearray(good.to_bytes())
    tampered = bytearray(raw)
    i = raw.index(text.encode()[:1])  # first byte of the text
    tampered[i] ^= 0x01
    cases = {
        "forgery-altered-text": (wid, bytes(tampered), "invalid"),
        "forgery-swapped-id": (os.urandom(8), bytes(raw), "invalid"),
        "forgery-untrusted-signer": (
            wid,
            trust.sign(wid, pl.Payload(text=text), untrusted).to_bytes(),
            "untrusted",
        ),
    }
    for name, (w, data, expect) in cases.items():
        plan = engine.make_plan(pats, w, data, rgb.shape[0], rgb.shape[1])
        y = rgb.astype(np.float32) @ np.array([0.299, 0.587, 0.114], np.float32)
        marked = np.clip(
            np.rint(rgb + plan.delta(y, {engine.variant_for_id(w): 1.0})[..., None]), 0, 255
        ).astype(np.uint8)
        rep = vm.detect_image_data(ImageData(marked), name)
        v = rep.verification or {}
        ok = (
            (v.get("signature") == "invalid")
            if expect == "invalid"
            else (v.get("signature") == "valid" and v.get("trust") == "untrusted")
        )
        out.append(
            {
                **base,
                "attack": name,
                "group": "forgery",
                "polarity": "forgery",
                "status": rep.status,
                "signature": v.get("signature"),
                "trust": v.get("trust"),
                "authentic": rep.authentic,
                "correctly_rejected": bool(ok and not rep.authentic),
                "payload_recovered": rep.payload is not None,
            }
        )
    return out


# ------------------------------------------------------------------ videos


def _make_source_video(sample: datasets.VideoSample, path: Path) -> None:
    from veilmark.video import ffmpeg

    if sample.filters == "PAN":
        import cv2
        import skimage.data as skd

        img = cv2.resize(skd.stereo_motorcycle()[0], (2400, 1620), interpolation=cv2.INTER_LANCZOS4)
        still = path.with_suffix(".png")
        cv2.imwrite(str(still), cv2.cvtColor(img, cv2.COLOR_RGB2BGR))
        ffmpeg.run(
            [
                "-loop",
                "1",
                "-framerate",
                "30",
                "-t",
                "6",
                "-i",
                str(still),
                "-vf",
                "crop=1280:720:'(iw-1280)*t/6':'(ih-720)*(0.5+0.4*sin(t))'",
                "-c:v",
                "libx264",
                "-crf",
                "16",
                "-pix_fmt",
                "yuv420p",
                str(path),
            ]
        )
        still.unlink()
        return
    ffmpeg.run(
        [
            *sample.ffmpeg_input,
            "-c:v",
            "libx264",
            "-crf",
            "16",
            "-pix_fmt",
            "yuv420p",
            "-c:a",
            "aac",
            str(path),
        ]
    )


def _video_job(
    home: str,
    sample_name: str,
    extra_path: str | None,
    seed: int,
    attack_names: list[str],
    strength: float,
    work: str,
) -> list[dict[str, Any]]:
    from veilmark.api import Veilmark, WatermarkSpec
    from veilmark.video import ffmpeg

    vm = Veilmark(Path(home))
    wdir = Path(work) / f"{sample_name}-{seed}"
    wdir.mkdir(parents=True, exist_ok=True)
    src = wdir / "source.mp4"
    if extra_path:
        shutil.copy(extra_path, src)
        split, kind = "user", "user"
    else:
        smp = next(v for v in datasets.VIDEOS if v.name == sample_name)
        _make_source_video(smp, src)
        split, kind = smp.split, smp.kind
    rng = np.random.default_rng([seed, _stable(sample_name)])
    text = _text(rng)
    marked = wdir / "marked.mp4"
    t0 = time.perf_counter()
    emb = vm.embed_video(src, marked, WatermarkSpec(text=text, strength=strength, identity="bench-trusted"))
    embed_s = time.perf_counter() - t0
    info = ffmpeg.probe(src)
    base = {
        "media": "video",
        "sample": sample_name,
        "split": split,
        "kind": kind,
        "seed": seed,
        "width": info.width,
        "height": info.height,
        "fps": float(info.fps),
        "duration": info.duration,
        "chip_px": emb.chip_px,
        "psnr_db": emb.psnr_db,
        "payload_bytes": emb.payload_bytes,
        "embed_seconds": round(embed_s, 2),
        "marked_size": marked.stat().st_size,
        "source_size": src.stat().st_size,
    }
    records = []
    for name in attack_names:
        a = next(x for x in atk.VIDEO_ATTACKS if x.name == name)
        for polarity, inp in (("positive", marked), ("negative", src)):
            if polarity == "negative" and name not in ("none", "h264-crf23", "downscale-480p", "crop-moving"):
                continue  # negatives on a representative subset (video detection is slow)
            outp = wdir / f"{polarity}-{name}{a.ext}"
            try:
                ffmpeg.run(["-i", str(inp), *a.args, "-an", str(outp)])
                t1 = time.perf_counter()
                rep = vm.detect_video(outp)
                dt = time.perf_counter() - t1
                v = rep.verification or {}
                records.append(
                    {
                        **base,
                        "attack": name,
                        "group": a.group,
                        "expected": a.expected,
                        "params": a.params,
                        "polarity": polarity,
                        "status": rep.status,
                        "detected": rep.detected,
                        "id_match": rep.watermark_id == emb.watermark_id if polarity == "positive" else False,
                        "payload_match": bool(rep.payload and rep.payload.get("text") == text)
                        if polarity == "positive"
                        else False,
                        "wrong_payload": bool(
                            polarity == "positive" and rep.payload and rep.payload.get("text") != text
                        ),
                        "signature": v.get("signature"),
                        "authentic": rep.authentic,
                        "sync_z": rep.confidence.get("sync_z"),
                        "detect_seconds": round(dt, 2),
                        "attacked_bytes": outp.stat().st_size,
                        "frames_analysed": rep.diagnostics.get("frames_analysed"),
                        "variants_observed": rep.diagnostics.get("variants_observed"),
                    }
                )
            except Exception as e:
                records.append(
                    {**base, "attack": name, "polarity": polarity, "error": f"{type(e).__name__}: {e}"}
                )
            finally:
                outp.unlink(missing_ok=True)
    return records


# ------------------------------------------------------------------ driver


def run(cfg: BenchConfig, progress: Callable[[float, str], None] | None = None) -> dict[str, Any]:
    from veilmark.benchmarks import report as report_mod

    prof = PROFILES[cfg.profile]
    seeds = cfg.seeds or prof["seeds"]
    cfg.out_dir.mkdir(parents=True, exist_ok=True)
    home = Path(tempfile.mkdtemp(prefix="veilmark-bench-"))
    work = Path(tempfile.mkdtemp(prefix="veilmark-bench-media-"))
    started = time.time()
    jobs: list[tuple[Any, ...]] = []
    try:
        _setup_home(home)
        if cfg.media in ("image", "both"):
            names = cfg.attack_names or prof["image_attacks"] or [a.name for a in atk.IMAGE_ATTACKS]
            atk.image_attacks(names)  # validate
            samples = [s for s in datasets.images(cfg.split, cfg.image_names) if datasets.available(s)]
            if prof["max_images"]:
                samples = samples[: prof["max_images"]]
            for s in samples:
                for seed in range(seeds):
                    jobs.append(("image", s.name, None, seed, names))
            for p in cfg.extra_images:
                jobs.append(("image", p.name, str(p), 0, names))
        if cfg.media in ("video", "both"):
            vnames = cfg.video_attack_names or prof["video_attacks"] or [a.name for a in atk.VIDEO_ATTACKS]
            atk.video_attacks(vnames)
            vids = datasets.videos(cfg.split)
            if prof["max_videos"]:
                vids = vids[: prof["max_videos"]]
            for v in vids:
                jobs.append(("video", v.name, None, 0, vnames))
            for p in cfg.extra_videos:
                jobs.append(("video", p.name, str(p), 0, vnames))
        records: list[dict[str, Any]] = []
        jsonl = (cfg.out_dir / "records.jsonl").open("w")
        with ProcessPoolExecutor(max_workers=cfg.workers) as ex:
            futs = []
            for kind, name, extra, seed, names in jobs:
                if kind == "image":
                    futs.append(ex.submit(_image_job, str(home), name, extra, seed, names, cfg.strength))
                else:
                    futs.append(
                        ex.submit(_video_job, str(home), name, extra, seed, names, cfg.strength, str(work))
                    )
            for i, f in enumerate(as_completed(futs)):
                try:
                    recs = f.result()
                except Exception as e:
                    recs = [{"error": f"job failed: {type(e).__name__}: {e}"}]
                for r in recs:
                    jsonl.write(json.dumps(r, default=str) + "\n")
                jsonl.flush()
                records += recs
                if progress:
                    progress((i + 1) / len(futs), f"{i + 1}/{len(futs)} jobs")
        jsonl.close()
        meta = {
            "split": cfg.split,
            "profile": cfg.profile,
            "media": cfg.media,
            "seeds": seeds,
            "strength": cfg.strength,
            "workers": cfg.workers,
            "jobs": len(jobs),
            "started": started,
            "seconds": round(time.time() - started, 1),
        }
        summary = report_mod.write_all(records, meta, cfg.out_dir)
        return summary
    finally:
        shutil.rmtree(home, ignore_errors=True)
        if not cfg.keep_media:
            shutil.rmtree(work, ignore_errors=True)
